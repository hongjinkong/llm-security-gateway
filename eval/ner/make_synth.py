def person(r: random.Random) -> str:
    return r.choices(list(SURNAMES), list(SURNAMES.values()))[0] + r.choice(GIVEN)


def address(r: random.Random) -> str:
    """도로명 주소(상세 있음·없음), 지번 주소, 아파트 동·호. 시·도는 긴 이름·짧은 이름·생략이 섞인다(시·군·구가 '시'로 시작할 때만 생략)."""
    long, short, sigungus = r.choice(REGIONS)
    sigungu = r.choice(sorted(sigungus))
    roads, dongs = sigungus[sigungu]
    head = r.choice((long, short, None if sigungu.split()[0].endswith("시") else long))
    head = f"{head} {sigungu}" if head else sigungu
    form = r.choices(("road", "road_floor", "road_unit", "jibun", "apt"), (40, 20, 15, 15, 10))[0]
    if form == "jibun":
        return f"{head} {r.choice(dongs)} {r.randrange(1, 980)}-{r.randrange(1, 60)}"
    if form == "apt":
        return f"{head} {r.choice(dongs)} {r.choice(APTS)}아파트 {r.randrange(101, 120)}동 {r.randrange(1, 25)}{r.randrange(1, 5):02d}호"
    num = str(r.randrange(1, 480)) + (f"-{r.randrange(1, 30)}" if r.random() < 0.2 else "")
    road = r.choice(roads) + (f"{r.randrange(2, 90)}길" if r.random() < 0.25 else "")
    floor = r.randrange(2, 30)
    tail = {"road": "", "road_floor": f", {floor}층", "road_unit": f" {floor}층 {floor}{r.randrange(1, 20):02d}호"}[form]
    return f"{head} {road} {num}{tail}"


# --- 조사 -----------------------------------------------------------------------
_DIGIT_FINAL = {"0": "ㅇ", "1": "ㄹ", "2": "", "3": "ㅁ", "4": "", "5": "", "6": "ㄱ", "7": "ㄹ", "8": "ㄹ", "9": ""}
_ZERO_FINAL = {1: "ㅂ", 2: "ㄱ", 3: "ㄴ", 4: "ㄴ"}   # 끝이 0이면 자리 이름으로 읽는다 — 십·백·천·만


def final(text: str) -> str:
    """마지막 글자를 읽었을 때의 받침('' 없음, 'ㄹ', 그 밖은 대표로 'ㅇ'). 숫자는 한자어로 읽는다(152 = 백오십이, 150 = 백오십)."""
    text = text.rstrip(")]")          # '제일정밀(주)'는 괄호 안 '주'를 읽는다
    c = text[-1]
    if "가" <= c <= "힣":
        jong = (ord(c) - 0xAC00) % 28
        return "" if jong == 0 else "ㄹ" if jong == 8 else "ㅇ"
    if c.isdigit():
        run = re.search(r"\d+$", text).group(0)     # type: ignore[union-attr]
        zeros = len(run) - len(run.rstrip("0"))
        return _ZERO_FINAL.get(zeros, "ㄴ") if zeros and run.strip("0") else _DIGIT_FINAL[c]
    raise ValueError(f"조사를 고를 수 없는 끝 글자: {c!r}")


def josa(prev: str, pair: str) -> str:
    with_final, without = pair.split("/")
    f = final(prev)
    if pair == "으로/로":
        return "로" if f in ("", "ㄹ") else "으로"
    return without if f == "" else with_final


# --- 조립 -----------------------------------------------------------------------
SLOT_RE = re.compile(r"\{(P3|P2|P|EO|E|A2|A|O|S|N)\}|\{(은/는|이/가|을/를|과/와|으로/로|이고/고)\}")
KIND = {"P": "person", "P2": "person", "P3": "person", "E": "person", "A": "address", "A2": "address", "O": "org", "S": "org", "EO": "org"}


def value(slot: str, r: random.Random) -> str:
    if slot in ("P", "P2", "P3"):
        return person(r)
    if slot in ("A", "A2"):
        return address(r)
    pool = {"E": EN_NAMES, "O": ORGS, "S": SCHOOLS, "EO": EN_ORGS}.get(slot)
    return r.choice(pool) if pool else str(r.randrange(30, 90))


def fill(template: str, r: random.Random) -> tuple[str, list[dict]]:
    values: dict[str, str] = {}
    out, spans, pos = "", [], 0
    for m in SLOT_RE.finditer(template):
        out += template[pos:m.start()]
        pos = m.end()
        slot = m.group(1)
        if slot is None:                                  # 조사 — 바로 앞까지 만든 글자를 본다
            out += josa(out, m.group(2))
            continue
        if slot not in values:
            v = value(slot, r)
            while v in values.values():                   # 한 문장 안의 두 사람·두 주소는 서로 다르다
                v = value(slot, r)
            values[slot] = v
        if slot in KIND:
            spans.append({"kind": KIND[slot], "start": len(out), "end": len(out) + len(values[slot])})
        out += values[slot]
    return out + template[pos:], spans


def render() -> str:
    r = random.Random(SEED)
    rows: list[dict] = []
    seen: set[str] = set()
    for t_idx, (domain, template) in enumerate(TEMPLATES, 1):
        made = 0
        while made < PER_TEMPLATE:
            text, spans = fill(template, r)
            if text in seen:
                continue
            seen.add(text)
            made += 1
            rows.append({"id": f"synth-t{t_idx:02d}-{made}", "domain": domain, "text": text, "spans": spans})
    for n, text in enumerate(NEGATIVES, 1):
        rows.append({"id": f"synth-neg-{n:02d}", "domain": "negative", "text": text, "spans": []})
    return "".join(json.dumps(row, ensure_ascii=False) + "\n" for row in rows)


